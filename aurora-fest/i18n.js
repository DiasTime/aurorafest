const RU = {};
let lang = 'ru';
let captured = false;

function capture() {
  document.querySelectorAll('[data-i18n]').forEach((el) => { RU[el.dataset.i18n] = el.textContent; });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => { RU[el.dataset.i18nAria] = el.getAttribute('aria-label'); });
  captured = true;
}

export function setLang(next) {
  if (!captured) capture();
  lang = next === 'en' ? 'en' : 'ru';
  const dict = lang === 'en' ? EN : RU;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const v = dict[el.dataset.i18n];
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const v = dict[el.dataset.i18nAria];
    if (v != null) el.setAttribute('aria-label', v);
  });
  try { localStorage.setItem('ac-lang', lang); } catch (err) { /* storage can be unavailable */ }
  return lang;
}

export function storedLang() {
  try { return localStorage.getItem('ac-lang') || 'ru'; } catch (err) { return 'ru'; }
}

export const getLang = () => lang;
export const d = (key, vars = {}) => {
  let s = DYN[lang][key];
  if (typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
};
